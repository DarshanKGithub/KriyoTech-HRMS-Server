"""Generate response types from local Pydantic schemas; no database access."""
import importlib
import json
from pathlib import Path


def ts_type(schema):
    if '$ref' in schema:
        return schema['$ref'].split('/')[-1]
    if 'anyOf' in schema:
        return ' | '.join(dict.fromkeys(ts_type(item) for item in schema['anyOf']))
    if 'enum' in schema:
        return ' | '.join(json.dumps(item) for item in schema['enum'])
    if 'const' in schema:
        return json.dumps(schema['const'])
    kind = schema.get('type')
    if kind == 'array':
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == 'object':
        if 'properties' in schema:
            return '{ ' + '; '.join(f'{name}: {ts_type(value)}' for name, value in schema['properties'].items()) + ' }'
        additional = schema.get('additionalProperties')
        return f'Record<string, {ts_type(additional) if isinstance(additional, dict) else "unknown"}>'
    return {'string': 'string', 'integer': 'number', 'number': 'number', 'boolean': 'boolean', 'null': 'null'}.get(kind, 'unknown')


def main():
    definitions = {}
    for module_name in ('employee', 'document', 'tenancy', 'payroll', 'performance', 'financials', 'dashboard_extended', 'leave', 'notifications'):
        module = importlib.import_module(f'app.schemas.{module_name}')
        for name, value in vars(module).items():
            if isinstance(value, type) and value.__module__ == module.__name__ and (name.endswith('Public') or name.endswith('Dashboard') or name in ('SalaryHistoryItem', 'CalendarResponse', 'MySpaceDashboard', 'OrganizationDashboard')):
                schema = value.model_json_schema()
                definitions.update(schema.pop('$defs', {}))
                definitions[name] = schema
    lines = ['// Generated by the backend tools/generate_ui_types.py. Do not edit manually.', '']
    for name, schema in sorted(definitions.items()):
        lines.append(f'export type {name} = {ts_type(schema)};')
        lines.append('')
    destination = Path(__file__).resolve().parents[2] / 'AviCorex-HRMS-UI' / 'types' / 'api.generated.ts'
    destination.write_text('\n'.join(lines), encoding='utf-8')
    print(f'Generated {len(definitions)} response types: {destination.name}')


if __name__ == '__main__':
    main()
